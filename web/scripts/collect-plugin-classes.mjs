// Make the utilities used by plugin browser bundles visible to Tailwind.
//
// Plugin bundles style themselves with the host's utility classes, but Tailwind only scans sources under
// this app and the Turbopack project root is `web/`, so `@source "../../plugins/…"` is refused outright
// ("leaves the filesystem root"). Any utility a plugin used and the host did not was therefore never
// generated, and the plugin page silently rendered without it.
//
// So the plugin sources are mirrored into ONE generated text blob inside this app, which globals.css
// scans with @source. A blob rather than copied .tsx files on purpose: it cannot be imported, so there is
// no second copy of the code to drift or be edited by mistake. It is regenerated by every web build and
// dev start (see the build/dev scripts) and gitignored — never a checked-in artifact to go stale.
import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const webRoot = dirname(here);
const OUT = join(webRoot, 'app', 'styles', 'plugin-classes.txt');

/** Every `plugins/<name>/web-src` TypeScript source, recursively. Tests live beside the components and
 *  are included: a class only a test asserts on is still a class the built CSS has to carry. */
function sourceFiles(pluginsDir) {
  if (!existsSync(pluginsDir)) return [];
  const out = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) walk(path);
      else if (/\.tsx?$/.test(entry.name)) out.push(path);
    }
  };
  for (const plugin of readdirSync(pluginsDir, { withFileTypes: true })) {
    if (!plugin.isDirectory()) continue;
    const webSrc = join(pluginsDir, plugin.name, 'web-src');
    if (existsSync(webSrc)) walk(webSrc);
  }
  return out.sort();
}

/** The blob Tailwind scans: each source's full text, so the extractor sees exactly the candidates it
 *  would see in the file itself. Returns the text so a test can assert on it without writing to disk. */
export function collectPluginClassSources(repoRoot) {
  const files = sourceFiles(join(repoRoot, 'plugins'));
  const parts = files.map((file) => `/* ${file} */\n${readFileSync(file, 'utf8')}`);
  return `/* GENERATED by web/scripts/collect-plugin-classes.mjs — do not edit. */\n${parts.join('\n')}\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, collectPluginClassSources(dirname(webRoot)));
  console.log(`[collect-plugin-classes] wrote ${OUT}`);
}
