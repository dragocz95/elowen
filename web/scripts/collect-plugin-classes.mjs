// Make the utilities used by plugin browser bundles visible to Tailwind.
//
// Plugin bundles style themselves with the host's utility classes, but Tailwind only scans sources under
// this app and the Turbopack project root is `web/`, so `@source "../../plugins/…"` is refused outright
// ("leaves the filesystem root"). Any utility a plugin used and the host did not was therefore never
// generated, and the plugin page silently rendered without it.
//
// So the plugin sources are mirrored into ONE generated text blob inside this app, which globals.css
// scans with @source. A blob rather than copied .tsx files on purpose: it cannot be imported, so there is
// no second copy of the code to drift or be edited by mistake. It is regenerated by every web build and
// dev start (see the build/dev scripts) and gitignored — never a checked-in artifact to go stale.
import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { homedir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const webRoot = dirname(here);
const OUT = join(webRoot, 'app', 'styles', 'plugin-classes.txt');

/** The writable plugin root outside the package — where an installed (non-bundled) plugin lives.
 *  Mirrors the daemon's own resolution (brainCore: `dirname(dbPath)/plugins`) rather than importing it,
 *  because the web app must not import src/. Not every environment that builds the web has one, so the
 *  caller treats a missing directory as "no user plugins", never as an error. */
export function userPluginsDir(env) {
  const db = env.ELOWEN_DB || join(env.HOME || homedir() || '/', '.config', 'elowen', 'elowen.db');
  return join(dirname(db), 'plugins');
}

/** Every file whose text can carry a utility class for one plugin: its `web-src` TypeScript sources
 *  (tests included — a class only a test asserts on is still a class the built CSS has to carry), or,
 *  for a plugin that ships only its built browser bundle, that bundle. The class names survive bundling
 *  as ordinary string literals, so scanning the bundle is what makes an INSTALLED plugin's page styled
 *  at all — it has no sources on disk to scan. */
function pluginFiles(pluginDir) {
  const out = [];
  const webSrc = join(pluginDir, 'web-src');
  if (existsSync(webSrc)) {
    const walk = (dir) => {
      for (const entry of readdirSync(dir, { withFileTypes: true })) {
        const path = join(dir, entry.name);
        if (entry.isDirectory()) walk(path);
        else if (/\.tsx?$/.test(entry.name)) out.push(path);
      }
    };
    walk(webSrc);
    return out;
  }
  const bundle = join(pluginDir, 'web', 'index.js');
  if (existsSync(bundle)) out.push(bundle);
  return out;
}

function sourceFiles(pluginsDir) {
  if (!existsSync(pluginsDir)) return [];
  const out = [];
  for (const plugin of readdirSync(pluginsDir, { withFileTypes: true })) {
    if (!plugin.isDirectory()) continue;
    out.push(...pluginFiles(join(pluginsDir, plugin.name)));
  }
  return out.sort();
}

/** The blob Tailwind scans: each source's full text, so the extractor sees exactly the candidates it
 *  would see in the file itself. Returns the text so a test can assert on it without writing to disk.
 *
 *  Both plugin roots are scanned — the bundled ones in the repo AND the installed ones in the data
 *  directory — because "a plugin" is not "a plugin we shipped". LIMITATION: this runs at web BUILD
 *  time, so a plugin installed afterwards is only covered by the next web build; a distribution that
 *  ships a prebuilt web app needs the plugin to carry its own generated CSS instead. */
export function collectPluginClassSources(repoRoot, env = process.env) {
  const files = [...sourceFiles(join(repoRoot, 'plugins')), ...sourceFiles(userPluginsDir(env))];
  const parts = files.map((file) => `/* ${file} */\n${readFileSync(file, 'utf8')}`);
  return `/* GENERATED by web/scripts/collect-plugin-classes.mjs — do not edit. */\n${parts.join('\n')}\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, collectPluginClassSources(dirname(webRoot)));
  console.log(`[collect-plugin-classes] wrote ${OUT}`);
}
